const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('web/app.js','utf8');
const nodes=Object.fromEntries(['#activity-list','#activity-more','#activity-status','#activity-toggle','#activity-panel'].map(k=>[k,{innerHTML:'',textContent:'',scrollTop:72,hidden:false,disabled:false,setAttribute(){},classList:{toggle(){return true}}}]));
let page,fail=false,calls=[];
const context={console,$:k=>nodes[k],esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;'),Date,api:async path=>{calls.push(path);if(fail)throw Error('offline');return page;}};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('// Activity view.'),source.indexOf('// End Activity view.')),context);
(async()=>{
 const event=(id,title)=>({id,item_id:'item-'+id,title,created:'2026-10-14T00:00:'+String(id).padStart(2,'0')+'Z',category:'Google Doc',action:'imported',historical:0});
 page={events:[event(3,'<Roadmap>'),event(2,'Second')],has_more:true};
 await context.refreshActivity();
 assert(nodes['#activity-list'].innerHTML.includes('&lt;Roadmap>'));
 assert(nodes['#activity-list'].innerHTML.includes('data-activity-item="item-3"'));
 assert.equal(nodes['#activity-list'].scrollTop,72);
 page={events:[event(1,'Earlier')],has_more:false};
 await context.refreshActivity(true);
 assert(calls.at(-1).includes('before_id=2'));
 assert(nodes['#activity-list'].innerHTML.includes('Earlier'));
 page={events:[event(4,'New import'),event(3,'<Roadmap>')],has_more:true};
 await context.refreshActivity();
 assert(nodes['#activity-list'].innerHTML.includes('Earlier'));
 assert(nodes['#activity-list'].innerHTML.indexOf('New import')<nodes['#activity-list'].innerHTML.indexOf('Earlier'));
 assert.equal(nodes['#activity-list'].scrollTop,72);
 fail=true;await context.refreshActivity();
 assert(nodes['#activity-status'].textContent.includes('unavailable'));
 assert.equal(nodes['#activity-more'].disabled,false);
 fail=false;await context.refreshActivity();
 assert(nodes['#activity-status'].textContent.includes('Successful'));
 console.log('Activity rendering, escaping, links, pagination, retained history/scroll and retry verified.');
})().catch(e=>{console.error(e);process.exit(1)});
