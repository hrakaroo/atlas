// embedweb generates Go string literals directly from the canonical web bytes.
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
)

func main() {
	source := flag.String("source", "../web", "Canonical web directory")
	output := flag.String("output", "internal/assets/generated.go", "Generated Go source")
	check := flag.Bool("check", false, "Fail if committed generated bytes are stale")
	flag.Parse()
	if flag.NArg() != 0 {
		fail(fmt.Errorf("unexpected positional arguments"))
	}
	var code bytes.Buffer
	fmt.Fprintln(&code, "// Code generated by tools/embedweb from canonical web files. DO NOT EDIT.\npackage assets\nimport \"os\"")
	fmt.Fprintln(&code, "func ReadFile(name string) ([]byte,error) { switch name {")
	for _, name := range []string{"index.html", "app.js", "style.css"} {
		data, err := os.ReadFile(filepath.Join(*source, name))
		if err != nil {
			fail(err)
		}
		fmt.Fprintf(&code, "// Canonical %s SHA-256: %x\ncase %s: return []byte(%s), nil\n", name, sha256.Sum256(data), strconv.Quote(name), strconv.Quote(string(data)))
	}
	fmt.Fprintln(&code, "default: return nil, os.ErrNotExist } }")
	generated, err := format.Source(code.Bytes())
	if err != nil {
		fail(err)
	}
	if *check {
		existing, err := os.ReadFile(*output)
		if err != nil {
			fail(err)
		}
		if !bytes.Equal(existing, generated) {
			fail(fmt.Errorf("embedded web assets are stale; run go generate ./internal/assets"))
		}
		return
	}
	if err := os.MkdirAll(filepath.Dir(*output), 0755); err != nil {
		fail(err)
	}
	if err := os.WriteFile(*output, generated, 0644); err != nil {
		fail(err)
	}
}
func fail(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }
